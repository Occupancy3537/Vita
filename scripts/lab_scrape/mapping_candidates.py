out = []
for mcode, m in LAB_CATALOG.items():
    variants = [norm(m["name"])] + [norm(v) for v in SYN.get(mcode, [])]
    variants = [v for v in set(variants) if v]
    for lab in ("gemotest", "invitro", "tafi", "unilab"):
        found = []
        for v in variants:
            for (lab2, nm), rr in singles.items():
                if lab2 != lab:
                    continue
                for r in rr:
                    n = norm(r["name"])
                    if n == v or (v and n.startswith(v + " ")):
                        found.append(r)
        # уникальные коды
        seen = {}
        for r in found:
            seen.setdefault(r["external_code"], r)
        for code, r in sorted(seen.items()):
            out.append({"marker": mcode, "marker_name": m["name"], "lab": lab,
                        "code": code, "name": r["name"][:80], "price": r["price"],
                        "url": r["url"], "raw_ref": r["raw_ref"],
                        "match": "prefix" if norm(r["name"]) not in variants else "exact"})

