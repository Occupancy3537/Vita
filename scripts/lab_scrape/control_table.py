def find(rows_by_lab, lab, variants):
    """Детерминированный матчинг для контрольной таблицы: точное совпадение
    нормализованного названия ИЛИ позиция начинается с варианта как префикса
    по словам («креатинин» ловит «Креатинин (венозная кровь)» — у сайтов
    суффиксы биоматериала). Все хиты показываются целиком с url/raw_ref —
    таблицу читает человек, ничего не подставляется."""
    hits = []
    want = {norm(v) for v in variants}
    for r in rows_by_lab.get(lab, []):
        nm = norm(r.get("name") or "")
        if nm in want or any(nm.startswith(v + " ") for v in want if v):
            hits.append(r)
    return hits


def main(argv) -> int:
    args = [a for a in argv if not a.startswith("--")]
    csv_out = None
    if "--csv" in argv:
        csv_out = argv[argv.index("--csv") + 1]
    if not args:
        print(__doc__)
        return 2
    rows = json.load(open(args[0], encoding="utf-8"))
    by_lab: dict[str, list] = {}
    for r in rows:
        by_lab.setdefault(r["lab_code"], []).append(r)
    labs = ["gemotest", "invitro", "tafi", "unilab"]
    table = []
    for marker, variants in MARKERS:
        for lab in labs:
            hits = find(by_lab, lab, variants)
            if not hits:
                table.append({"маркер": marker, "лаба": lab, "код": "—", "название": "",
                              "цена": "нет в собранном прайсе", "url": "", "raw_ref": "",
                              "city_confirmed": ""})
            for h in hits:
                table.append({"маркер": marker, "лаба": lab,
                              "код": h.get("external_code"), "название": h.get("name"),
                              "цена": h.get("price"), "url": h.get("url") or "",
                              "raw_ref": h.get("raw_ref") or "",
                              "city_confirmed": h.get("city_confirmed")})
    if csv_out:
        with open(csv_out, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(table[0].keys()), delimiter=";")
            w.writeheader()
            w.writerows(table)
        print(f"CSV: {csv_out}")
    for t in table:
        print(f"{t['маркер']:28} | {t['лаба']:9} | {str(t['код']):12} | "
              f"{str(t['цена']):10} | {t['название'][:48]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
