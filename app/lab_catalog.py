_TIME_PHRASE_RX = re.compile(r"через\s+(\d+)\s*(?:[-–—]\s*(\d+)\s*)?(недел|месяц|дн)", re.I)
_UNIT_DAYS = {"дн": 1, "недел": 7, "месяц": 30}


def parse_relative_days(text: str) -> Optional[int]:
    """«через 4-6 недель» -> 28 (консервативно — МЕНЬШАЯ граница диапазона,
    Часть 1.2: где неуверенность в диапазоне — не давать событию просрочиться
    позже, чем нужно). Работает на СЫРОМ тексте (не app.registrar.norm() —
    тот вырезает дефис между границами диапазона, разрушая "4-6")."""
    m = _TIME_PHRASE_RX.search(str(text or "").lower().replace("ё", "е"))
    if not m:
        return None
    lo = int(m.group(1))
    unit = m.group(3)
    return lo * _UNIT_DAYS[unit]


def find_markers_in_text(text: str) -> set[str]:
    """Ищет упоминания маркеров/панелей в свободном тексте (заголовок/повод
    рекомендации). Переиспользует app.registrar.SYN (тот же словарь, что
    распознаёт лабораторные документы) — не заводим второй список синонимов.
    Точное совпадение слова (ключ ≥3 символа) ИЛИ совпадение по началу слова
    для ключей ≥4 символов (тот же приём, что registrar.resolve_id — покрывает
    русские падежи: "билирубином" начинается с "билирубин").

    Ключи короче 3 символов (например "по" -> M074 «протромбиновое
    отношение», "na" -> M029) в SYN нужны registrar.py для сравнения ЦЕЛОГО
    имени показателя из колонки документа — там нет риска. В СВОБОДНОМ ТЕКСТЕ
    предложения такой ключ ложно сработает на обычном слове ("по расписанию",
    самостоятельно найдено при живой проверке на реальной рекомендации,
    2026-09-26) — поэтому здесь короче 3 символов ключи не рассматриваются
    вообще, даже как точное совпадение слова."""
    from app.registrar import SYN, norm
    words = norm(text).split()
    wordset = set(words)
    found: set[str] = set()
    for key, code in SYN.items():
        if len(key) < 3:
            continue
        if key in wordset:
            found.add(code)
            continue
        if len(key) >= 4:
            for w in words:
                if w.startswith(key):
                    found.add(code)
                    break
    for key, codes in PANEL_TEXT_ALIASES.items():
        for w in words:
            if w.startswith(key):
                found.update(codes)
                break
    return found
